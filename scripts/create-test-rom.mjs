import { mkdir,writeFile } from 'node:fs/promises';
const rom=new Uint8Array(32768).fill(0xff),code=[];
const emit=(...b)=>code.push(...b), labels={},fixups=[];
const mark=n=>labels[n]=code.length, branch=(opcode,label)=>{emit(opcode,0);fixups.push([code.length-1,label]);};
emit(0x78,0xd8,0x18,0xfb,0xc2,0x10,0xa2,0xff,0x1f,0x9a,0xe2,0x20); // native, 8-bit A, 16-bit X
emit(0xa9,0x80,0x8d,0x00,0x21,0xa9,0x01,0x8d,0x00,0x42); // forced blank, auto joypad
emit(0xa9,0x0f,0x8d,0x00,0x21);
emit(0xa9,0x42,0x8f,0x00,0x00,0x70); // marker in battery-backed cartridge RAM
mark('vblank');emit(0xad,0x12,0x42);branch(0x10,'vblank');
mark('joy');emit(0xad,0x12,0x42,0x29,0x01);branch(0xd0,'joy');
emit(0x9c,0x21,0x21,0xad,0x19,0x42,0x29,0x80);branch(0xd0,'green');
emit(0xa9,0x1f,0x8d,0x22,0x21,0xa9,0x00,0x8d,0x22,0x21);branch(0x80,'end');
mark('green');emit(0xa9,0xe0,0x8d,0x22,0x21,0xa9,0x03,0x8d,0x22,0x21);
mark('end');emit(0xad,0x12,0x42);branch(0x30,'end');branch(0x80,'vblank');
for(const [position,label] of fixups)code[position]=(labels[label]-position-1)&255;
rom.set(code);rom.set(new TextEncoder().encode('VIDEOGAMES INPUT TEST '.slice(0,21)),0x7fc0);
rom.set([0x20,2,5,1,1,0,0],0x7fd5);rom.set([0,0,0,0],0x7fdc);
for(const p of [0x7fe4,0x7fe6,0x7fea,0x7fee,0x7ff4,0x7ff8,0x7ffa,0x7ffc,0x7ffe])rom.set([0,0x80],p);
const sum=(rom.reduce((s,v)=>s+v,0)+510)&65535;rom[0x7fdc]=(~sum)&255;rom[0x7fdd]=((~sum)>>8)&255;rom[0x7fde]=sum&255;rom[0x7fdf]=sum>>8;
await mkdir('.qa',{recursive:true});await writeFile('.qa/videogames-input-test.sfc',rom);console.log('ROM de prueba original creada en .qa/.');
